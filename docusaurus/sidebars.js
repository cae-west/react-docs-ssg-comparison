// Builds Docusaurus sidebars straight from React's own sidebar*.json files
// (../sidebars). Nothing is hand-written and the content is never touched.
const fs = require('fs');
const path = require('path');

const CONTENT = path.resolve(__dirname, '../content');
const SIDEBARS = path.resolve(__dirname, '../sidebars');

// Map a react.dev URL path (e.g. /learn/state) to a Docusaurus doc id.
function docIdFor(routePath) {
  if (routePath === '/' || routePath === '') return 'home'; // content/index.md has `id: home`
  const rel = routePath.replace(/^\//, '');
  if (fs.existsSync(path.join(CONTENT, rel + '.md'))) return rel;
  if (fs.existsSync(path.join(CONTENT, rel, 'index.md'))) return rel + '/index';
  return null;
}

function build(sidebarFile) {
  const used = new Set();
  const missing = [];

  function convert(node) {
    if (node.hasSectionHeader) {
      return {type: 'html', value: node.sectionHeader, className: 'sidebar-section-header'};
    }
    if (node.path && /^https?:\/\//.test(node.path)) {
      return {type: 'link', label: node.title, href: node.path};
    }
    const id = node.path ? docIdFor(node.path) : null;
    if (!id && node.path) missing.push(node.path);
    const reusable = id && !used.has(id);
    if (reusable) used.add(id);

    if (node.routes && node.routes.length) {
      const items = node.routes.map(convert).filter(Boolean);
      const cat = {type: 'category', label: node.title, collapsed: true, items};
      if (reusable) cat.link = {type: 'doc', id};
      return cat;
    }
    if (reusable) return {type: 'doc', id, label: node.title};
    return null;
  }

  const data = JSON.parse(fs.readFileSync(path.join(SIDEBARS, sidebarFile), 'utf8'));
  const items = data.routes.map(convert).filter(Boolean);
  if (missing.length) console.warn(`[sidebars] ${sidebarFile}: ${missing.length} path(s) with no matching file`, missing.slice(0, 5));
  return items;
}

module.exports = {
  learn: build('sidebarLearn.json'),
  reference: build('sidebarReference.json'),
  community: build('sidebarCommunity.json'),
  blog: build('sidebarBlog.json'),
  // Pages React's sidebars don't list: warnings, errors, versions
  extras: [
    'versions',
    {type: 'category', label: 'Warnings', items: [{type: 'autogenerated', dirName: 'warnings'}]},
    {type: 'category', label: 'Errors', items: [{type: 'autogenerated', dirName: 'errors'}]},
  ],
};
